/* ═══════════════════════════════════════════════════════════════════════════
   MAKE RESTORE ADMIN-ONLY  —  install as src/archive-admin-guard.js
   ═══════════════════════════════════════════════════════════════════════════
       node /home/abed/apps/isp-monitoring/ip-manager-backend/src/archive-admin-guard.js
       node .../archive-admin-guard.js --apply     (writes; without it, dry run)

   THE PROBLEM. The Recycle Bin screen ships in the frontend now. Its sidebar
   entry is hidden from anyone without manageUsers — but that is chrome, not
   enforcement. `POST /archive/:id/restore` is reachable by anyone holding a
   valid token, and restoring a deleted subnet, client or user is not an
   ordinary-operator action: it writes rows back into live tables.

   WHAT THIS INSTALLS. A middleware, `requireAdmin`, on that one route.

   IT ASKS THE DATABASE, NOT THE TOKEN. The obvious implementation is
   `if (req.user.role !== 'admin')`. That trusts a claim carried in the JWT,
   which means anyone who can mint or alter a token grants themselves restore —
   and it also breaks silently the moment the token's shape changes, in the
   direction of ALLOWING rather than denying. So the identifier comes from the
   token and the ROLE comes from a fresh query against the users table. A
   revoked admin loses restore immediately rather than at token expiry.

   IT FAILS CLOSED. Cannot identify the caller, cannot find the row, query
   throws — all of them deny. Restore is a rare, recoverable-by-asking action;
   a guard that opens on error is not a guard.

   IT DISCOVERS YOUR SCHEMA. Which column carries the role, and whether it is a
   name or an id pointing at a roles table, differs between deployments and I
   am not going to guess it. This reads information_schema, prints exactly what
   it found, and refuses to write anything it could not verify.

   IT IS A FILE, NOT A `node -e`, on purpose: `!` inside double quotes in an
   interactive bash is history expansion and rewrites the command before node
   sees it. That has cost a round trip here before.
   ═══════════════════════════════════════════════════════════════════════════ */

const fs = require('fs');
const path = require('path');

const APP = '/home/abed/apps/isp-monitoring/ip-manager-backend';
const APPLY = process.argv.includes('--apply');
const NEEDLE = 'const ARCHIVE = {';
const ROUTE = "router.post('/:id/restore'";

function fail(m) { console.error('FAILED: ' + m); process.exit(1); }
function note(m) { console.log('  ' + m); }

/* The middleware source, as a function so a test can generate and EXERCISE the
   real artifact rather than a copy of it — see test/admin-guard.mjs. */
function buildGuard(SQL) {
  return `/* GENERATED by BACKEND_ADMIN_ONLY_RESTORE.js — safe to edit, but read the
   reasoning in that file first.

   Restoring from the Recycle Bin writes rows back into live tables. It is an
   administrator action, and the frontend hiding the button is not enforcement.

   THE ROLE IS READ FROM THE DATABASE, NOT FROM THE TOKEN. Trusting a role
   claim in a JWT means anyone who can mint or alter a token grants themselves
   restore, and it fails in the direction of ALLOWING when the token shape
   changes. The identifier comes from the token; the role is looked up fresh,
   so a revoked admin loses restore immediately rather than at token expiry.

   IT FAILS CLOSED. No identifiable caller, no matching row, or a query that
   throws — all deny. */
const pool = require('./db');

const ADMIN_ROLES = ['admin', 'administrator', 'root', 'superadmin', 'super admin', 'super_admin'];

const LOOKUP = ${JSON.stringify(SQL)};

async function requireAdmin(req, res, next) {
  const u = req.user || {};
  /* Every field a token in this codebase has been seen to carry. The first
     one present wins; the lookup matches it against id OR username. */
  const ident = u.id ?? u.user_id ?? u.uuid ?? u.username ?? u.user_name ?? u.sub ?? u.email;

  if (ident === undefined || ident === null || String(ident).trim() === '') {
    return res.status(401).json({ ok: false, error: 'Not signed in.' });
  }

  try {
    const { rows } = await pool.query(LOOKUP, [String(ident)]);
    const row = rows[0];
    if (row === undefined) {
      console.warn('[archive] restore denied: no user row for ' + String(ident));
      return res.status(403).json({ ok: false, error: 'Restoring is limited to administrators.' });
    }

    const ok = row.admin_flag === true
      || ADMIN_ROLES.indexOf(String(row.role || '').trim().toLowerCase()) >= 0;

    if (ok !== true) {
      console.warn('[archive] restore denied for ' + String(ident) + ' (role "' + row.role + '")');
      return res.status(403).json({ ok: false, error: 'Restoring is limited to administrators.' });
    }

    return next();
  } catch (err) {
    /* A guard that opens when it cannot decide is not a guard. */
    console.error('[archive] restore guard could not resolve the caller:', err.message);
    return res.status(403).json({ ok: false, error: 'Could not verify your permissions.' });
  }
}

module.exports = requireAdmin;
`;
}
if (require.main !== module) { module.exports = { buildGuard }; }


(async () => {
  let pool;
  try { pool = require(path.join(APP, 'src/db')); }
  catch (e) { fail('could not load src/db: ' + e.message); }

  /* ── 1. What does the schema actually look like? ───────────────────────── */
  const { rows } = await pool.query(
    "SELECT table_name, column_name FROM information_schema.columns WHERE table_schema = 'public'");
  const cols = new Map();
  for (const r of rows) {
    if (cols.has(r.table_name) === false) cols.set(r.table_name, new Set());
    cols.get(r.table_name).add(r.column_name);
  }

  const USERS = ['ip_manager_users', 'users', 'app_users'].find(t => cols.has(t));
  if (USERS === undefined) fail('no users table found (looked for ip_manager_users, users, app_users)');
  const uc = cols.get(USERS);
  note('users table: ' + USERS);

  /* The column that identifies a row, and the ones a token might carry. */
  const idCol = ['id', 'user_id', 'uuid'].find(c => uc.has(c));
  const nameCol = ['username', 'user_name', 'login', 'email'].find(c => uc.has(c));
  if (idCol === undefined && nameCol === undefined)
    fail(USERS + ' has neither an id nor a username column');
  note('identity columns: ' + [idCol, nameCol].filter(Boolean).join(', '));

  /* Is the role a name on the row, or an id pointing somewhere? */
  const roleNameCol = ['role', 'role_name', 'user_role'].find(c => uc.has(c));
  const roleIdCol   = ['role_id'].find(c => uc.has(c));
  const ROLES = ['user_roles', 'roles', 'platform_roles'].find(t => cols.has(t));
  const rolesNameCol = ROLES ? ['role_name', 'name', 'title'].find(c => cols.get(ROLES).has(c)) : null;
  const rolesIdCol   = ROLES ? ['role_id', 'id'].find(c => cols.get(ROLES).has(c)) : null;
  const adminFlagCol = ['is_admin', 'is_superuser', 'admin'].find(c => uc.has(c));

  if (roleNameCol) note('role: ' + USERS + '.' + roleNameCol + ' (a name on the row)');
  else if (roleIdCol && ROLES && rolesNameCol && rolesIdCol)
    note('role: ' + USERS + '.' + roleIdCol + ' -> ' + ROLES + '.' + rolesNameCol);
  else if (adminFlagCol) note('role: ' + USERS + '.' + adminFlagCol + ' (a boolean flag)');
  else fail('could not work out how this schema records a role. Send me the output of:\n'
    + "  select column_name from information_schema.columns where table_name='" + USERS + "'");

  /* ── 2. Build the one query the guard will run ─────────────────────────── */
  const where = [];
  if (idCol)   where.push('u.' + idCol + '::text = $1');
  if (nameCol) where.push('lower(u.' + nameCol + '::text) = lower($1)');

  let select, from;
  if (roleNameCol) {
    select = 'u.' + roleNameCol + '::text AS role, false AS admin_flag';
    from = USERS + ' u';
  } else if (adminFlagCol) {
    select = "'' AS role, coalesce(u." + adminFlagCol + ', false) AS admin_flag';
    from = USERS + ' u';
  } else {
    select = 'coalesce(r.' + rolesNameCol + "::text, '') AS role, false AS admin_flag";
    from = USERS + ' u LEFT JOIN ' + ROLES + ' r ON r.' + rolesIdCol + ' = u.' + roleIdCol;
  }
  const SQL = 'SELECT ' + select + ' FROM ' + from + ' WHERE ' + where.join(' OR ') + ' LIMIT 1';
  note('lookup: ' + SQL);

  /* ── 3. The middleware ─────────────────────────────────────────────────── */
  const guard = buildGuard(SQL);

  /* ── 4. Find the archive router and wire it in ─────────────────────────── */
  const found = [];
  (function walk(dir, depth) {
    if (depth > 3) return;
    let entries = [];
    try { entries = fs.readdirSync(dir, { withFileTypes: true }); } catch (e) { return; }
    for (const e of entries) {
      const p = path.join(dir, e.name);
      if (e.isDirectory()) { if (e.name !== 'node_modules') walk(p, depth + 1); continue; }
      if (e.name.endsWith('.js') === false) continue;
      if (p === __filename) continue;
      let src = '';
      try { src = fs.readFileSync(p, 'utf8'); } catch (e2) { continue; }
      if (src.includes(NEEDLE) && src.includes(ROUTE)) found.push(p);
    }
  })(path.join(APP, 'src'), 0);

  if (found.length === 0) fail('no file has both ' + NEEDLE + ' and ' + ROUTE);
  if (found.length > 1)  fail('more than one candidate: ' + found.join(', '));

  const target = found[0];
  const before = fs.readFileSync(target, 'utf8');
  note('archive router: ' + target);

  if (before.includes('requireAdmin')) {
    console.log('\nAlready guarded — requireAdmin is present in ' + target + '. Nothing to do.');
    process.exit(0);
  }

  const guardPath = path.join(APP, 'src/require-admin.js');
  const rel = './' + path.relative(path.dirname(target), guardPath).split(path.sep).join('/')
    .replace(/^\.\//, '');
  const requireLine = "const requireAdmin = require('" + (rel.startsWith('.') ? rel : './' + rel) + "');\n";

  /* The require goes after the last top-level require, the guard goes into the
     route signature. Both are single, unambiguous edits. */
  const lastRequire = before.lastIndexOf("require(");
  const lineEnd = before.indexOf('\n', lastRequire) + 1;
  let after = before.slice(0, lineEnd) + requireLine + before.slice(lineEnd);
  after = after.replace(ROUTE + ', async (req, res) => {', ROUTE + ', requireAdmin, async (req, res) => {');
  if (after.includes('requireAdmin, async') === false) {
    /* Signature written differently — do not guess, say so. */
    fail('the restore route signature is not the expected `' + ROUTE
      + ", async (req, res) => {`. Send me the line and I will adjust this script.");
  }

  /* Re-parse both files before keeping either. pm2 must never see a broken one. */
  const vm = require('vm');
  try { new vm.Script(guard, { filename: guardPath }); }
  catch (e) { fail('the generated middleware does not parse: ' + e.message); }
  try { new vm.Script(after, { filename: target }); }
  catch (e) { fail('the edited router does not parse, nothing was changed: ' + e.message); }

  if (APPLY !== true) {
    console.log('\nDRY RUN — nothing written. Both files parse. Re-run with --apply to install:');
    console.log('  + ' + guardPath + '   (new)');
    console.log('  ~ ' + target + '   (adds requireAdmin to the restore route)');
    process.exit(0);
  }

  fs.writeFileSync(guardPath, guard, 'utf8');
  fs.copyFileSync(target, target + '.bak-' + Date.now());
  fs.writeFileSync(target, after, 'utf8');

  console.log('\nwrote ' + guardPath);
  console.log('guarded the restore route in ' + target + ' (.bak- copy beside it)');
  console.log('');
  console.log('now:  pm2 restart ip-manager-backend');
  console.log('then, as a NON-admin, this must answer 403:');
  console.log('  curl -s -o /dev/null -w "%{http_code}\\n" -X POST -H "Authorization: Bearer <their token>" \\');
  console.log('    http://10.249.2.9/api/ip-manager/archive/1/restore');
  console.log('and as an admin it must NOT be 403.');
  process.exit(0);
})().catch(e => fail(e.message));
